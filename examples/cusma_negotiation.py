"""CUSMA multi-party trade negotiation — full MARL demo with real LLMs.

Three country workflows (USA, Canada, Mexico) negotiate terms of a simplified
CUSMA/USMCA trade agreement over multiple rounds inside an
:class:`~choreo_mini.core.episode.Episode`.  Every proposal is generated by a
real OpenAI LLM; the episode runs until either rewards stabilise (Nash
convergence proxy) or ``max_rounds`` is reached.

Prerequisites
-------------
Set your OpenAI API key as an environment variable — never hardcode it::

    export OPENAI_API_KEY=sk-proj-...

Then run::

    python examples/cusma_negotiation.py

Optional env vars::

    CUSMA_MODEL=gpt-4o-mini          # model to use (default: gpt-4o-mini)
    CUSMA_MAX_ROUNDS=6               # max negotiation rounds (default: 6)
    CUSMA_CONVERGENCE_WINDOW=3       # convergence window (default: 3)

Output is written to output/cusma_trace.ndjson.

Architecture
------------
::

    Episode (max_rounds)
    ├── USAWorkflow      → AgentNode("USANegotiator",    llm=gpt-4o-mini)
    ├── CanadaWorkflow   → AgentNode("CanadaNegotiator", llm=gpt-4o-mini)
    └── MexicoWorkflow   → AgentNode("MexicoNegotiator", llm=gpt-4o-mini)

Each round:
  1. Every country reads the current env_state (others' last proposals).
  2. Each negotiator produces a structured proposal (JSON-ish key/value block).
  3. A reward function scores convergence by measuring token overlap across
     proposals; when all three countries are within threshold the episode ends.

This example is deliberately kept to a single file so it can be shared and
run without modification.
"""

