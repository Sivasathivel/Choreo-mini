def _parse_ready(text: str) -> bool:
    return bool(re.search(r"READY_TO_STOP\s*:\s*YES", text, re.IGNORECASE))


def _parse_stop_reason(text: str) -> str:
    m = re.search(r"STOP_REASON\s*:\s*(.+)", text, re.IGNORECASE)
    return m.group(1).strip() if m else ""


def _parse_section(text: str, header: str) -> str:
    """Extract content under a ## HEADER section."""
    pattern = rf"##\s*{re.escape(header)}\s*\n(.*?)(?=\n##|\nREADY_TO_STOP|\Z)"
    m = re.search(pattern, text, re.IGNORECASE | re.DOTALL)
    return m.group(1).strip() if m else ""


def _all_parties_satisfied(step, trajectory) -> bool:
    """Episode ends when every party signals READY_TO_STOP: YES for its own reason."""
    return all(_parse_ready(action) for action in step.actions.values())


def _token_overlap(a: str, b: str) -> float:
    ta = set(re.findall(r"\b\w+\b", a.lower()))
    tb = set(re.findall(r"\b\w+\b", b.lower()))
    if not ta or not tb:
        return 0.0
    return len(ta & tb) / len(ta | tb)


def _reward_fn(
    env_state: Dict[str, Any],
    actions: Dict[str, str],
    round_n: int,
) -> Dict[str, float]:
    """1.0 when READY_TO_STOP: YES; else Jaccard position-stability proxy."""
    prev_proposals = env_state.get("proposals", {})
    rewards: Dict[str, float] = {}
    for country, proposal in actions.items():
        if _parse_ready(proposal):
            rewards[country] = 1.0
        elif prev_proposals.get(country):
            rewards[country] = round(_token_overlap(proposal, prev_proposals[country]), 4)
        else:
            rewards[country] = 0.0
    return rewards


def _urgency_block(round_n: int, max_rounds: int) -> str:
    """Escalating urgency message injected into the prompt each round."""
    remaining = max_rounds - round_n
    if remaining == 0:
        return (
            "⚠ FINAL ROUND — DEADLOCK RISK: If no agreement is reached this round, "
            "CUSMA Article 34.7 activates the annual review mechanism, any party may issue "
            "a 6-month withdrawal notice, and tariffs revert to MFN schedules. "
            "The cost of deadlock is highest for the party most dependent on the current arrangement."
        )
    if remaining == 1:
        return (
            f"⚠ Only 1 round remains after this one. A deadlock will activate Article 34.7 annual "
            f"review and open the 6-month withdrawal-notice window. Structural concessions or "
            f"creative domestic-policy packages are needed to avoid deadlock costs."
        )
    if remaining <= 3:
        return (
            f"⚠ {remaining} rounds remaining. Urgency is rising — positions must move meaningfully. "
            f"A deadlock is costly for all parties, but most costly for the most CUSMA-dependent one."
        )
    return f"{remaining} round(s) remaining after this one."


