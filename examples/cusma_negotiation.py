"""CUSMA multi-party trade negotiation — full MARL demo with real LLMs.

Three country workflows (USA, Canada, Mexico) negotiate terms of a CUSMA/USMCA
trade agreement over multiple rounds inside an
:class:`~choreo_mini.core.episode.Episode`.  Every proposal is generated by a
real OpenAI LLM; the episode runs until either all parties signal
``READY_TO_STOP: YES`` (each for asymmetric reasons) or ``max_rounds`` is
reached (triggering a deadlock outcome).

Prerequisites
-------------
Set your OpenAI API key as an environment variable — never hardcode it::

    export OPENAI_API_KEY=sk-proj-...

Then run::

    python examples/cusma_negotiation.py

Optional env vars::

    CUSMA_MODEL=gpt-4o-mini     # model to use (default: gpt-4o-mini)
    CUSMA_MAX_ROUNDS=8          # max negotiation rounds (default: 8)

Output is written to output/cusma_trace.ndjson.

Architecture
------------
::

    Episode (max_rounds)
    ├── USAWorkflow      → AgentNode("USANegotiator",    llm=gpt-4o-mini)
    ├── CanadaWorkflow   → AgentNode("CanadaNegotiator", llm=gpt-4o-mini)
    └── MexicoWorkflow   → AgentNode("MexicoNegotiator", llm=gpt-4o-mini)

Each round:
  1. Every country reads the current env_state (others' last proposals).
  2. Each negotiator produces a dual-format proposal — a negotiating position
     at the table AND domestic policy measures taken unilaterally.
  3. Each party self-reports READY_TO_STOP: YES/NO at the end of its proposal.
  4. The episode ends when ALL parties signal YES (for different reasons).
  5. If max_rounds is exhausted first, a deadlock outcome is reported with
     Article 34.7 annual-review and 6-month withdrawal-notice implications.
"""

