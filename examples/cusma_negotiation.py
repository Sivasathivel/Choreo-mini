class _CountryWorkflow(Workflow):
    """Base class for a country negotiator."""

    country: str = ""
    system_prompt: str = ""

    def __init__(self, llm: Any, observability=None) -> None:
        super().__init__(
            f"{self.country.lower()}_workflow",
            enable_profiling=True,
            observability=observability,
        )
        self._negotiator = AgentNode(
            self,
            f"{self.country}Negotiator",
            role=self.system_prompt,
            llm=llm,
        )
        self.proposals: List[str] = []

    def propose(self, env_state: Dict[str, Any], round_n: int) -> str:
        """Called by the Episode each round; returns this country's proposal."""
        others = {
            k: v for k, v in env_state.get("proposals", {}).items()
            if k != self.country and v
        }
        context_block = ""
        if others:
            context_block = "\n\nOther parties' positions (previous round):\n" + "\n---\n".join(
                f"[{country}]\n{proposal}" for country, proposal in others.items()
            )

        urgency = _urgency_block(round_n, MAX_ROUNDS)

        prompt = (
            f"=== CUSMA Negotiation — Round {round_n} of {MAX_ROUNDS} ===\n"
            f"{urgency}\n\n"
            f"Reference areas (not exhaustive — raise any CUSMA-relevant interest):\n"
            + "\n".join(f"  • {a}" for a in REFERENCE_AREAS) +
            f"{context_block}\n\n"
            f"State your updated position. Use the required three-section format:\n\n"
            f"## NEGOTIATING POSITION\n"
            f"[Demands and offers at the table — be specific. Reference specific proposals from "
            f"other parties. Acknowledge progress but hold or advance your position.]\n\n"
            f"## DOMESTIC POLICY MEASURES\n"
            f"[Unilateral actions you are taking at home regardless of the outcome — "
            f"these signal your BATNA and reduce your dependency on the negotiated deal.]\n\n"
            f"## IN OUR NATIONAL INTEREST\n"
            f"[WHY this round's combination of negotiating position AND domestic policy is in your "
            f"national interest — for your citizens' prosperity (GAGI trajectory), political "
            f"sustainability, and strategic autonomy. Show how the domestic measures reinforce or "
            f"compensate for the negotiating stance. Be honest about trade-offs.]\n\n"
            f"End with exactly:\n"
            f"READY_TO_STOP: YES or NO\n"
            f"STOP_REASON: one sentence"
        )

        response = self.send(f"{self.country}Negotiator", prompt).content
        self.proposals.append(response)
        return response


